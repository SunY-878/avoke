import Foundation
import CryptoKit

public enum ClipboardKind: String, Codable, Sendable { case text, link, image, files }

public struct ClipboardEntry: Identifiable, Codable, Equatable, Sendable {
    public var id: UUID
    public var kind: ClipboardKind
    public var text: String
    public var data: Data?
    public var fileURLs: [String]
    public var date: Date
    public var source: String
    public var isPinned: Bool

    public init(id: UUID = UUID(), kind: ClipboardKind, text: String = "", data: Data? = nil,
                fileURLs: [String] = [], date: Date = Date(), source: String = "", isPinned: Bool = false) {
        self.id = id; self.kind = kind; self.text = text; self.data = data; self.fileURLs = fileURLs
        self.date = date; self.source = source; self.isPinned = isPinned
    }

    public var fingerprint: String {
        var bytes = Data((kind.rawValue + "\u{1f}" + text + "\u{1f}" + fileURLs.joined(separator: "\u{1f}")).utf8)
        if let data { bytes.append(data) }
        return SHA256.hash(data: bytes).map { String(format: "%02x", $0) }.joined()
    }

    public var title: String {
        switch kind {
        case .image: return "图片"
        case .files:
            let first = fileURLs.first.flatMap(URL.init(string:))?.lastPathComponent ?? "文件"
            return fileURLs.count > 1 ? "\(first) 等 \(fileURLs.count) 个文件" : first
        case .text, .link:
            return String(text.trimmingCharacters(in: .whitespacesAndNewlines).split(separator: "\n").first ?? "文本")
        }
    }

    public func matches(_ query: String) -> Bool {
        query.isEmpty || (text + " " + title + " " + source).localizedCaseInsensitiveContains(query)
    }

    public static func isSensitive(types: [String]) -> Bool {
        let excluded = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
                        "com.agilebits.onepassword"]
        return types.contains { type in excluded.contains { type.hasPrefix($0) } }
    }
}

public struct ClipboardHistory {
    public private(set) var entries: [ClipboardEntry]
    public var limit: Int
    public init(entries: [ClipboardEntry] = [], limit: Int = 100) {
        self.entries = entries; self.limit = max(1, limit); trim()
    }

    public mutating func insert(_ entry: ClipboardEntry) {
        var entry = entry
        if let index = entries.firstIndex(where: { $0.fingerprint == entry.fingerprint }) {
            let previous = entries.remove(at: index)
            entry.id = previous.id; entry.isPinned = previous.isPinned
        }
        entries.insert(entry, at: 0); trim()
    }

    public mutating func remove(_ id: UUID) { entries.removeAll { $0.id == id } }
    public mutating func togglePin(_ id: UUID) {
        guard let index = entries.firstIndex(where: { $0.id == id }) else { return }
        entries[index].isPinned.toggle(); trim()
    }
    public mutating func clear() { entries.removeAll() }
    public mutating func trim() {
        let pins = Set(entries.filter(\.isPinned).prefix(20).map(\.id))
        var unpinned = 0
        entries = entries.filter { entry in
            if pins.contains(entry.id) { return true }
            unpinned += 1; return unpinned <= max(1, limit)
        }
        for index in entries.indices where entries[index].isPinned && !pins.contains(entries[index].id) {
            entries[index].isPinned = false
        }
    }
    public var sorted: [ClipboardEntry] {
        entries.sorted { $0.isPinned != $1.isPinned ? $0.isPinned : $0.date > $1.date }
    }
}
